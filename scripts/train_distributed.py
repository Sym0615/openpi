"""Build and run the InternA1 PyTorch config for single-process or DDP training."""

import dataclasses
import datetime
import faulthandler
import json
import os
from pathlib import Path
import socket
import sys
import traceback

faulthandler.enable(all_threads=True)


def _rank_context() -> str:
    return (
        f"host={socket.gethostname()} pid={os.getpid()} rank={os.environ.get('RANK', '?')} "
        f"local_rank={os.environ.get('LOCAL_RANK', '?')} world_size={os.environ.get('WORLD_SIZE', '?')}"
    )


def _status(message: str) -> None:
    print(f"[train-bootstrap] {_rank_context()} {message}", file=sys.stderr, flush=True)

_status("starting Python entrypoint imports")

try:
    from torch.distributed.elastic.multiprocessing.errors import record
    import train_pytorch

    import openpi.training.config as _config
except BaseException as exc:
    _status(f"import failed: {type(exc).__name__}: {exc}")
    traceback.print_exc()
    raise
else:
    _status("Python entrypoint imports complete")


@record
def main() -> None:
    _status("validating launcher environment and model weight paths")
    openpi_workdir = Path(os.environ["OPENPI_WORKDIR"])
    run_root = Path(os.environ["OPENPI_RUN_ROOT"])
    world_size = int(os.environ.get("WORLD_SIZE", "1"))
    rank = int(os.environ.get("RANK", "0"))
    weight_path = Path(os.environ.get("OPENPI_WEIGHT_PATH", "/datahub/public/model/pi05_base_pytorch_bf16"))
    model_file = weight_path / "model.safetensors"
    model_config_file = weight_path / "config.json"

    if not model_file.is_file():
        raise FileNotFoundError(f"Missing PyTorch model weights: {model_file}")

    if model_config_file.is_file():
        weight_config = json.loads(model_config_file.read_text(encoding="utf-8"))
        if int(weight_config.get("action_dim", 32)) != 32:
            raise ValueError(f"Expected action_dim=32 in {model_config_file}, got {weight_config.get('action_dim')}")
        if int(weight_config.get("action_horizon", 16)) != 16 and rank == 0:
            print(
                f"[train] weight action_horizon={weight_config.get('action_horizon')}; "
                "InternA1 training uses action_horizon=16. Weight compatibility will be checked during load.",
                flush=True,
            )

    distributed = world_size > 1
    run_id = os.environ.get("OPENPI_RUN_ID")
    if distributed and not run_id:
        raise ValueError("OPENPI_RUN_ID must be set for distributed training")
    run_id = run_id or datetime.datetime.now(datetime.UTC).strftime("%Y%m%d_%H%M%S")

    def env_int(name: str, default: int) -> int:
        return int(os.environ.get(name, default))

    def env_float(name: str, default: float) -> float:
        return float(os.environ.get(name, default))

    def env_bool(name: str, *, default: bool) -> bool:
        value = os.environ.get(name)
        if value is None:
            return default
        if value.lower() in {"1", "true", "yes", "on"}:
            return True
        if value.lower() in {"0", "false", "no", "off"}:
            return False
        raise ValueError(f"{name} must be a boolean value, got {value!r}")

    profiling_enabled = env_bool("OPENPI_PROFILE", default=False)
    torch_trace_enabled = env_bool("OPENPI_TORCH_TRACE", default=False)
    if torch_trace_enabled and not profiling_enabled:
        raise ValueError("OPENPI_TORCH_TRACE requires OPENPI_PROFILE=1")

    resume = env_bool("OPENPI_RESUME", default=False)
    # train_pytorch resolves this placeholder into <run_id>_<UTC start time>
    # after DDP initialization, with the timestamp generated by global rank 0.
    os.environ["OPENPI_TIMESTAMPED_RUN_DIR"] = "1"

    config = _config.get_config("pi05_interna1")
    config = dataclasses.replace(
        config,
        exp_name=run_id,
        checkpoint_base_dir=str(run_root),
        pytorch_weight_path=str(weight_path),
        pytorch_training_precision="bfloat16",
        num_train_steps=env_int("OPENPI_TRAIN_STEPS", 120 if profiling_enabled else 10000),
        batch_size=env_int("OPENPI_BATCH_SIZE", 64),
        save_interval=env_int("OPENPI_SAVE_INTERVAL", 1000),
        log_interval=env_int("OPENPI_LOG_INTERVAL", 1),
        overwrite=env_bool("OPENPI_OVERWRITE", default=not resume),
        resume=resume,
        wandb_enabled=env_bool("OPENPI_WANDB", default=False),
        num_workers=env_int("OPENPI_NUM_WORKERS", 16),
        profiling_enabled=profiling_enabled,
        profiling_warmup_steps=env_int("OPENPI_PROFILE_WARMUP_STEPS", 10),
        profiling_log_interval=env_int("OPENPI_PROFILE_LOG_INTERVAL", 1),
        profiling_torch_trace=torch_trace_enabled,
        profiling_trace_active_steps=env_int("OPENPI_TRACE_ACTIVE_STEPS", 20),
        gpu_monitor_interval_s=env_float("OPENPI_GPU_MONITOR_INTERVAL", 1.0),
    )

    if rank == 0:
        print(f"[train] workdir={openpi_workdir}", flush=True)
        print(
            f"[train] run_dir_template={config.checkpoint_dir.parent}/{run_id}_<UTC start time>",
            flush=True,
        )
        print(f"[train] weights={config.pytorch_weight_path}", flush=True)
        print(f"[train] CUDA_VISIBLE_DEVICES={os.environ['CUDA_VISIBLE_DEVICES']}", flush=True)
        print(
            f"[train] mode={'profiling' if profiling_enabled else 'training'} "
            f"distributed={distributed} world_size={world_size} "
            f"profiling={config.profiling_enabled} torch_trace={config.profiling_torch_trace} "
            f"steps={config.num_train_steps} global_batch_size={config.batch_size} "
            f"num_workers_per_rank={config.num_workers} resume={config.resume} overwrite={config.overwrite}",
            flush=True,
        )

    if os.environ.get("OPENPI_DRY_RUN") == "1":
        if rank == 0:
            print("[train] dry run complete; training was not started", flush=True)
        return

    _status(f"configuration complete; entering train_loop checkpoint_dir={config.checkpoint_dir}")
    train_pytorch.init_logging()
    train_pytorch.train_loop(config)
    _status("train_loop completed successfully")


if __name__ == "__main__":
    try:
        main()
    except BaseException as exc:
        _status(f"fatal error: {type(exc).__name__}: {exc}")
        traceback.print_exc()
        sys.stderr.flush()
        sys.stdout.flush()
        raise
